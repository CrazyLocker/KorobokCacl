-- «Лак» пропал из калькулятора: в V10 операция была выключена вместе с
-- остальными неиспользуемыми (is_active = false), и калькулятор, который
-- показывает только активные операции, перестал её рисовать.
-- Технолог лаком пользуется, поэтому возвращаем операцию в справочник под
-- коротким именем, которое видно в строке «Дополнительные операции».
-- Цена и единица измерения остаются прежними (12 ₽ за м²).
UPDATE operations
SET name      = 'Лак',
    is_active = true
WHERE name = 'УФ-лак';
