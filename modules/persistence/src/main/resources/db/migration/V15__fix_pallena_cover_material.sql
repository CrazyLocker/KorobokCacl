-- ============================================================
-- V15: Паллена — крышка всегда базовый coated 35
-- ============================================================
-- Паллена — это Элара с «обработанной» крышкой. Базовый материал
-- крышки в справочнике — coated 35 (как у Элары); обработка
-- (дизайнерский картон, печать, тиснение) выбирается менеджером
-- в расчёте, а не хранится в справочнике конструкций.
--
-- Затрагивает только Паллену 4 и Паллену 42: у Паллены 9/16/25
-- крышка уже coated 35. perSheet не меняется, constructs/parts
-- количество не меняется.
-- ============================================================

UPDATE parts p
   SET material_id = (SELECT id FROM materials WHERE type = 'coated' AND price_per_sheet = 35 LIMIT 1)
  FROM constructs c
 WHERE p.construct_id = c.id
   AND c.name IN ('Паллена 4', 'Паллена 42')
   AND p.name = 'Крышка';
